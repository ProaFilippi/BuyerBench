"""
Script 02: Run Full Realistic Experiment (N=50 per cell)
=========================================================
Runs the REALISTIC_DESIGN manifest (10 models × 5 bias types × 2 variants
× 50 runs = 5,000 runs ≈ $750, ~15 hours).

GATE 1 ENFORCEMENT (Section O.3):
  Before executing, this script reads ``ceiling_effect.json`` from a completed
  pilot_full experiment directory and verifies Gate 1 has been cleared:
    1. Error rate < 5%  (infrastructure healthy)
    2. ≥2/10 models show mean_BSI > 0.05 on ≥1 bias type  (BSI variation exists)
  If Gate 1 has not passed, the script exits with status 1 to prevent spending
  ~$750 on an inconclusive run.  Use ``--skip-gate1`` to bypass this check.

GATE 2 ENFORCEMENT (Section O.3):
  Before executing, this script reads ``robustness_pilot.json`` from the
  robustness pilot directory and verifies Gate 2 has been cleared:
    BSI coefficient of variation across 3 prompt phrasings < 60%
  If Gate 2 has not passed, the script exits with status 1.
  Use ``--skip-gate2`` to bypass, or ``--mock`` to skip both gates.

Prerequisites:
  - OPENROUTER_API_KEY must be set (or pass --mock for local validation)
  - pip install -e ".[dev]" completed
  - A completed pilot_full run with ceiling_effect.json, generated by:
      python research/scripts/03_analyze_ceiling_effect.py \\
             --experiment-dir results/experiments/{pilot_full_dir}
  - A completed robustness pilot with robustness_pilot.json, generated by:
      python -m buyerbench robustness-pilot --agent <model>

Flags:
  --pilot-dir DIR       Path to completed pilot_full experiment directory
                        (must contain ceiling_effect.json).  Required unless
                        --skip-gate1 or --mock is passed.
  --skip-gate1          Bypass Gate 1 check.  Use only with explicit justification.
  --robustness-dir DIR  Path to directory containing robustness_pilot.json
                        (default: results/robustness-pilot).
  --skip-gate2          Bypass Gate 2 prompt-sensitivity check.  Use only with
                        explicit justification.
  --dry-run             Print plan + cost estimate without invoking any models.
  --resume              Skip already-completed runs (restart after crash).
  --mock                Substitute mock-agent-v1 for all models (free; validates
                        the full pipeline without API credentials or gates).
  --output-dir DIR      Override experiment output directory
                        (default: results/experiments).
  --no-pin-versions     Skip OpenRouter model-version pinning (offline / CI use).

Run: python research/scripts/02_run_full_experiment.py \\
         --pilot-dir results/experiments/{pilot_full_id} \\
         --robustness-dir results/robustness-pilot
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from research.experiments.grid import REALISTIC_DESIGN  # noqa: E402
from research.experiments.manifest import create_manifest, freeze_manifest  # noqa: E402
from research.experiments.run_experiment import (  # noqa: E402
    estimate_cost,
    generate_run_plan,
    run_experiment,
)

# Default location for the robustness pilot output written by
# `python -m buyerbench robustness-pilot --agent <model>`
_DEFAULT_ROBUSTNESS_DIR = _REPO_ROOT / "results" / "robustness-pilot"


# ── Gate 1 loader ─────────────────────────────────────────────────────────────


def load_gate1_result(pilot_dir: Path) -> dict:
    """Load the Gate 1 decision from ``ceiling_effect.json`` in *pilot_dir*.

    Returns the ``gate1`` sub-dict from the ceiling effect analysis.  Raises
    ``FileNotFoundError`` if the file is absent and ``KeyError`` if the ``gate1``
    key is missing (e.g., an older analysis was run before gate1 was added).
    """
    ceiling_path = pilot_dir / "ceiling_effect.json"
    if not ceiling_path.exists():
        raise FileNotFoundError(
            f"ceiling_effect.json not found in {pilot_dir}.\n"
            "Generate it first:\n"
            f"  python research/scripts/03_analyze_ceiling_effect.py "
            f"--experiment-dir {pilot_dir}"
        )
    data = json.loads(ceiling_path.read_text(encoding="utf-8"))
    if "gate1" not in data:
        raise KeyError(
            f"'gate1' key not found in {ceiling_path}. "
            "Re-run 03_analyze_ceiling_effect.py with the latest code."
        )
    return data["gate1"]


def check_gate1(pilot_dir: Path) -> None:
    """Exit with status 1 if Gate 1 has not been cleared.

    Reads ``ceiling_effect.json`` from *pilot_dir* and prints a summary.
    If ``gate1.proceed`` is False, prints the failure reason and raises
    ``SystemExit(1)``.
    """
    gate1 = load_gate1_result(pilot_dir)
    print("Gate 1 status:")
    print(f"  Criterion 1 (error rate)    : {gate1['criterion1_detail']}")
    print(f"  Criterion 2 (BSI variation) : {gate1['criterion2_detail']}")
    print(f"  Recommendation : {gate1['recommendation']}")
    print()

    if not gate1["proceed"]:
        print("ERROR: Gate 1 has NOT been cleared.  Aborting full experiment.")
        print("Fix the issues above and re-run the pilot_full experiment, then")
        print("re-analyze with 03_analyze_ceiling_effect.py before retrying.")
        print("(Pass --skip-gate1 to bypass this check at your own risk.)")
        raise SystemExit(1)

    print("[Gate 1 PASSED]  Proceeding to full N=50 realistic experiment.")
    print()


# ── Gate 2 loader ─────────────────────────────────────────────────────────────


def load_gate2_result(robustness_dir: Path) -> dict:
    """Load the Gate 2 decision from ``robustness_pilot.json`` in *robustness_dir*.

    Returns the full robustness pilot report dict.  Raises ``FileNotFoundError``
    if ``robustness_pilot.json`` is absent from *robustness_dir*.
    """
    pilot_file = Path(robustness_dir) / "robustness_pilot.json"
    if not pilot_file.exists():
        raise FileNotFoundError(
            f"robustness_pilot.json not found in {robustness_dir}.\n"
            "Generate it first:\n"
            "  python -m buyerbench robustness-pilot --agent <model> \\\n"
            f"      --output-dir {robustness_dir}"
        )
    return json.loads(pilot_file.read_text(encoding="utf-8"))


def check_gate2(robustness_dir: Path) -> None:
    """Exit with status 1 if Gate 2 has not been cleared.

    Reads ``robustness_pilot.json`` from *robustness_dir* and prints a summary.
    If ``overall_recommendation`` is not ``"PROCEED"``, prints the failure
    reason and raises ``SystemExit(1)``.
    """
    data = load_gate2_result(robustness_dir)
    overall = data.get("overall_recommendation", "")
    cv_threshold = data.get("cv_threshold", 0.60)
    scenarios_passing = data.get("scenarios_passing", 0)
    scenarios_failing = data.get("scenarios_failing", 0)
    to_redesign = data.get("scenarios_to_redesign", [])

    print("Gate 2 status:")
    print(f"  CV threshold          : {cv_threshold:.0%}")
    print(f"  Scenarios passing     : {scenarios_passing}")
    print(f"  Scenarios failing     : {scenarios_failing}")
    print(f"  Overall recommendation: {overall}")
    print()

    if overall != "PROCEED":
        print("ERROR: Gate 2 has NOT been cleared.  Aborting full experiment.")
        if to_redesign:
            print(f"  Scenarios to redesign: {', '.join(to_redesign)}")
        print("Redesign prompts and re-run the robustness pilot before retrying.")
        print("(Pass --skip-gate2 to bypass this check at your own risk.)")
        raise SystemExit(1)

    print("[Gate 2 PASSED]  Prompt sensitivity acceptable — proceeding to full experiment.")
    print()


# ── Main ──────────────────────────────────────────────────────────────────────


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        prog="python research/scripts/02_run_full_experiment.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--pilot-dir",
        type=Path,
        metavar="DIR",
        help=(
            "Path to the completed pilot_full experiment directory "
            "(must contain ceiling_effect.json).  Required unless --skip-gate1 "
            "or --mock is passed."
        ),
    )
    parser.add_argument(
        "--skip-gate1",
        action="store_true",
        help="Bypass Gate 1 check.  Use only with explicit justification.",
    )
    parser.add_argument(
        "--robustness-dir",
        type=Path,
        default=None,
        metavar="DIR",
        help=(
            "Path to directory containing robustness_pilot.json "
            f"(default: {_DEFAULT_ROBUSTNESS_DIR}).  Used for Gate 2 check."
        ),
    )
    parser.add_argument(
        "--skip-gate2",
        action="store_true",
        help="Bypass Gate 2 prompt-sensitivity check.  Use only with explicit justification.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print plan + cost estimate without invoking any models.",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Skip run_ids already present in runs.jsonl (restart after crash).",
    )
    parser.add_argument(
        "--mock",
        action="store_true",
        help=(
            "Replace all 10 real models with mock-agent-v1. "
            "Free and fast; implies --skip-gate1 (no pilot_dir required)."
        ),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/experiments"),
        metavar="DIR",
        help="Parent directory for experiment outputs (default: results/experiments).",
    )
    parser.add_argument(
        "--no-pin-versions",
        action="store_true",
        help="Skip OpenRouter model-version pinning (useful for offline / CI use).",
    )
    args = parser.parse_args(argv)

    # --mock implies --skip-gate1 and --skip-gate2: pipeline validation doesn't need a pilot.
    skip_gate1 = args.skip_gate1 or args.mock
    skip_gate2 = args.skip_gate2 or args.mock

    # Gate 1 enforcement.
    if not skip_gate1:
        if args.pilot_dir is None:
            parser.error(
                "--pilot-dir is required unless --skip-gate1 or --mock is passed.\n"
                "Point it to the completed pilot_full experiment directory that "
                "contains ceiling_effect.json."
            )
        check_gate1(args.pilot_dir)
    elif args.skip_gate1 and not args.mock:
        print("[--skip-gate1] Gate 1 check bypassed — proceeding without verification.")
        print()

    # Gate 2 enforcement.
    if not skip_gate2:
        robustness_dir = args.robustness_dir or _DEFAULT_ROBUSTNESS_DIR
        check_gate2(robustness_dir)
    elif args.skip_gate2 and not args.mock:
        print("[--skip-gate2] Gate 2 prompt-sensitivity check bypassed — proceeding without verification.")
        print()

    # Build design (swap in mock agent if requested).
    design = dict(REALISTIC_DESIGN)
    if args.mock:
        design = {
            **design,
            "models": ["mock-agent-v1"],
            "cost_per_run_usd": 0.00,
        }
        print("[--mock] Substituting mock-agent-v1 for all real models.")

    output_dir: Path = args.output_dir

    # 1. Build and freeze manifest.
    print(f"Building realistic manifest (N={design['n_runs_per_cell']} per cell)…")
    manifest = create_manifest(
        design,
        pin_model_versions=not args.no_pin_versions,
    )
    manifest_path = freeze_manifest(manifest, output_dir)
    exp_dir = manifest_path.parent
    print(f"Manifest written : {manifest_path}")

    # 2. Generate run plan and write run_plan.csv.
    manifest_dict = json.loads(manifest_path.read_text(encoding="utf-8"))
    runs = generate_run_plan(manifest_dict)
    run_plan_path = exp_dir / "run_plan.csv"
    with open(run_plan_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(runs[0].keys()))
        writer.writeheader()
        writer.writerows(runs)
    print(f"Run plan written : {run_plan_path}  ({len(runs):,} runs)")

    # 3. Write cost estimate.
    cost = estimate_cost(len(runs), design["cost_per_run_usd"])
    cost_path = exp_dir / "cost_estimate.txt"
    cost_path.write_text(json.dumps(cost, indent=2), encoding="utf-8")
    print(
        f"Cost estimate    : ${cost['estimated_total_usd']:.2f} for {cost['n_runs']:,} runs"
    )
    print()

    # 4. Execute or display dry-run summary.
    run_experiment(
        manifest_path=manifest_path,
        output_dir=exp_dir,
        dry_run=args.dry_run,
        resume=args.resume,
    )

    if not args.dry_run:
        print()
        print("Next step — analyze ceiling effect / run regressions:")
        print(
            f"  python research/scripts/03_analyze_ceiling_effect.py "
            f"--experiment-dir {exp_dir}"
        )
        print(f"  python research/scripts/03_run_regressions.py "
              f"--experiment-dir {exp_dir}")


if __name__ == "__main__":
    main()
