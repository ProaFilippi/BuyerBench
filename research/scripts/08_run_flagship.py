"""
Script 08: Run Flagship LLM Experiments (N=100 per cell; 8 bias types)
=======================================================================
Runs the FLAGSHIP_DESIGN manifest (10 models × 8 bias types × 17 scenario
slots × 2 temperatures × 2 prompt versions × 100 runs = 68,000 runs ≈
$13,600, ~50–60 hours).

FLAGSHIP EXPANSION (UPGRADE-8/9/10):
  The flagship design extends the realistic design's 5 standard bias types
  with three new types:
    - UPGRADE-8  p2-06-default       (status-quo / default bias)
    - UPGRADE-9  p2-07-loss-aversion (loss-aversion switching cost)
    - UPGRADE-10 p2-08-warp          (WARP transitivity triplet: AB, BC, AC)
  Two temperatures (0.7 and 0.0) and two prompt versions (standard and cot)
  are run in the same experiment to enable within-experiment robustness checks.
  WARP uses three scenario slots (warp_ab, warp_bc, warp_ac); all other bias
  types use two (baseline + treatment).  Total scenario slots = 17.

GATE 3 ENFORCEMENT (Section O.3):
  Before executing, this script verifies Gate 3 has been cleared from a
  completed full realistic N=50 experiment:
    1. ≥3/10 models show statistically detectable bias on ≥2/5 bias types
       (95% CI lower bound > 0 on treatment cells)
  If Gate 3 has not passed, the script exits with status 1.  An alternative
  "robust rationality" framing is suggested if all models show BSI ≈ 0.
  Use ``--skip-gate3`` to bypass this check.

  To generate the gate3.json file from a completed realistic experiment:
    python research/scripts/08_run_flagship.py --full-dir <realistic_dir> --analyze-gate3

Prerequisites:
  - OPENROUTER_API_KEY must be set (or pass --mock for local validation)
  - pip install -e ".[dev]" completed
  - A completed realistic N=50 experiment with cells.json, generated by:
      python research/scripts/02_run_full_experiment.py
      python research/scripts/02_aggregate_results.py --experiment-dir <dir>

Flags:
  --full-dir DIR      Path to the completed realistic N=50 experiment directory
                      (must contain cells.json or gate3.json).  Required unless
                      --skip-gate3 or --mock is passed.
  --skip-gate3        Bypass Gate 3 check.  Use only with explicit justification.
  --analyze-gate3     Compute gate3.json from cells.json in --full-dir, then exit.
  --dry-run           Print plan + cost estimate without invoking any models.
  --resume            Skip already-completed runs (restart after crash).
  --mock              Substitute mock-agent-v1 for all models (free; validates
                      the full pipeline without API credentials or Gate 3).
  --output-dir DIR    Override experiment output directory
                      (default: results/experiments).
  --no-pin-versions   Skip OpenRouter model-version pinning (offline / CI use).

Run: python research/scripts/08_run_flagship.py \\
         --full-dir results/experiments/{realistic_id}
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

